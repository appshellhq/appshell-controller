#!/usr/bin/env bash
# Writes the Helm chart's CRD template from the CRD controller-gen generates, so the chart can
# never install a schema the controller doesn't have. CI fails if the result isn't committed.
#
# Wrapped in crds.install, and annotated to be kept on uninstall when crds.keep, so removing the
# controller never deletes every AppshellApplication with it. A template rather than the chart's
# crds/ directory, which Helm installs once and never upgrades.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="${root}/charts/appshell-controller/templates/crds.yaml"

{
  echo '{{- /* Generated by hack/chart-crds.sh from config/crd/bases. Do not edit. */}}'
  echo '{{- if .Values.crds.install }}'
  for crd in "${root}"/config/crd/bases/*.yaml; do
    awk '
      # Add the keep annotation beside controller-gen'"'"'s own, once, under metadata.annotations.
      /^  annotations:$/ && !done {
        print
        print "    {{- if .Values.crds.keep }}"
        print "    helm.sh/resource-policy: keep"
        print "    {{- end }}"
        done = 1
        next
      }
      { print }
    ' "${crd}"
  done
  echo '{{- end }}'
} > "${out}"
